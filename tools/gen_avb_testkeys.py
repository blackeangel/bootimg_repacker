def key_bits(path):
    text = subprocess.run(["openssl", "rsa", "-in", path, "-noout", "-text"], check=True, capture_output=True).stdout.decode()
    first = text.splitlines()[0]  # "Private-Key: (2048 bit, 2 primes)" (older OpenSSL: "RSA Private-Key: (2048 bit, ...)")
    return int(first.split("(")[1].split(" ")[0])


def c_string(name, pem):
    lines = ["const char %s[] =" % name]
    for line in pem.decode("ascii").splitlines():
        lines.append('    "%s\\n"' % line)
    lines[-1] += ";"
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    found = []
    for name, file in KEYS:
        path = os.path.join(sys.argv[1], file)
        pem = open(path, "rb").read()
        assert b"\r" not in pem and pem.endswith(b"\n"), path
        found.append((name, file, pem, key_bits(path)))
    out = []
    out.append("""// SPDX-License-Identifier: MIT
//
// GENERATED by tools/gen_avb_testkeys.py -- do not edit by hand.
//
// The public test keys of the AVB project (platform/external/avb, test/data/*.pem). The private halves have been
// published with the project since its beginning; they are embedded only so that abr can sign an AVB 2.0 image again
// without a key of the person's own. When the image was signed with one of them the new signature is as good as the
// old one; when it was not, only a bootloader that does not check the key (or trusts these) accepts the result. They
// protect nothing: never use them for anything that has to stay trustworthy.
//""")
    for line in MIT.splitlines():
        out.append(("// " + line).rstrip())
    out.append("//")
    for name, file, pem, bits in found:
        out.append("//   %-22s sha256 %s  (%d bytes, %d-bit RSA)" % (file, hashlib.sha256(pem).hexdigest(), len(pem), bits))
    out.append("""#include "abr/avb_keys.hpp"

namespace abr::detail {
""")
    for i, (name, file, pem, bits) in enumerate(found):
        out.append(c_string("kPem%d" % i, pem))
        out.append("")
    out.append("const AvbTestKey kAvbTestKeys[] = {")
    for i, (name, file, pem, bits) in enumerate(found):
        out.append('    {"%s", %d, kPem%d},' % (name, bits, i))
    out.append("};")
    out.append("")
    out.append("const size_t kAvbTestKeyCount = sizeof(kAvbTestKeys) / sizeof(kAvbTestKeys[0]);")
    out.append("")
    out.append("}  // namespace abr::detail")
    print("\n".join(out))


main()
