"""Regenerates src/avb_testkeys.cpp from the public test keys of the AVB project.

    gen_avb_testkeys.py <external/avb>/test/data > src/avb_testkeys.cpp

The inputs are `testkey_rsa2048.pem`, `testkey_rsa4096.pem`, `testkey_rsa8192.pem` and `testkey_rsa2048_2.pem` of
`platform/external/avb` (`test/data`). They are the *public* test keys of the AVB project: the private halves have
been published with it since the project began, which is why AOSP's own build rules name them (the README of the
project has `BOARD_AVB_VBMETA_SYSTEM_KEY_PATH := external/avb/test/data/testkey_rsa2048.pem` and
`BOARD_AVB_BOOT_KEY_PATH := external/avb/test/data/testkey_rsa4096.pem` as examples) and why abr can use them as the
signer of last resort. Needs only Python and the `openssl` command (to read the size of a key).
"""
import hashlib
import os
import subprocess
import sys

KEYS = [  # (name, file): the first of a size is the one abr signs with when the image's own key is not known
    ("testkey_rsa2048", "testkey_rsa2048.pem"),
    ("testkey_rsa4096", "testkey_rsa4096.pem"),
    ("testkey_rsa8192", "testkey_rsa8192.pem"),
    ("testkey_rsa2048_2", "testkey_rsa2048_2.pem"),
]

# The permission notice of the project (avbtool.py, and LICENSE of external/avb for the rest).
