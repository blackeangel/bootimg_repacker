// abr::avb_keys -- the public test keys of the AVB project, built into abr, and the choice of the key that signs an AVB 2.0 image
// again (vbmeta.img, or the footer of boot, vendor_boot, dtbo and the like).
//
// An AVB 2.0 signature covers what is in the vbmeta, so an image whose content has changed needs a new one. Which key makes it:
//   1. a key of the person's own (keys/avb_key.pem in the unpacked folder) -- always, when there is one;
//   2. else, when nothing that the signature covers has changed, none: the signature the image has stays;
//   3. else one of the keys here: the one whose public key is the image's own (the image was signed with a public test key, so the new
//      signature is as valid as the old one was), and if the image's key is none of these, the first key of the size the algorithm
//      needs (a bootloader that checks the key against the one it trusts will reject that image, and abr says so).
//
// The private halves of these keys have been published with the AVB project (platform/external/avb, test/data) since it began; they
// protect nothing, and are here for exactly that reason.
#pragma once

#include <cstddef>
#include <cstdint>
#include <span>
#include <string>

#include "abr/byte_io.hpp"

namespace abr {

struct AvbTestKey {
    const char* name;  // the name of the key's file in the AVB project: "testkey_rsa4096"
    unsigned bits;     // the size of the RSA key: 2048, 4096 or 8192
    const char* pem;   // the private key (PEM, PKCS#1), as the project has it
};

namespace detail {
extern const AvbTestKey kAvbTestKeys[];  // avb_testkeys.cpp (generated by tools/gen_avb_testkeys.py)
extern const size_t kAvbTestKeyCount;
}  // namespace detail

// The keys, in the order of preference among those of one size.
std::span<const AvbTestKey> avb_test_keys();

// The one of them whose public key, in the form a vbmeta stores it (abr::avb_encode_public_key), is `public_key_blob`; null when it is
// none of them.
const AvbTestKey* find_avb_test_key(const Bytes& public_key_blob);

// What to say about an AVB public key (the blob of a vbmeta, or of a chain partition descriptor): its size, its SHA-1 (the id avbtool
// prints for it), and which of the test keys it is, when it is one: "4096-bit RSA, sha1 ab12...; the public AVB test key testkey_rsa4096".
std::string describe_avb_public_key(const Bytes& public_key_blob);

struct AvbKeyChoice {
    const AvbTestKey* key = nullptr;  // null: no test key signs for this algorithm (none, ML-DSA, or a number that is no algorithm)
    bool the_images_key = false;      // its public key is the one the image has
};

// The test key to sign with for `algorithm_type` (AvbAlgorithm) of an image whose vbmeta has `image_public_key`.
AvbKeyChoice choose_avb_test_key(uint32_t algorithm_type, const Bytes& image_public_key);

}  // namespace abr
